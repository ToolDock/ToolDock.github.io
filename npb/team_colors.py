"""球団の色。選手ページ・ドラフトの球団ページの見出しの帯に使う。

(地の色, 文字の色, 下の帯の色)。地が明るい球団（巨人・阪神）は文字を黒にする。
球団が公式に定める色の値ではなく、よく知られた色に近づけたもの。
"""

TEAM_COLORS = {
    "巨人": ("#F97709", "#000000", "#1a1a1a"),
    "阪神": ("#FFE100", "#000000", "#1a1a1a"),
    "DeNA": ("#0055A5", "#ffffff", "#00A0E9"),
    "横浜": ("#0055A5", "#ffffff", "#00A0E9"),
    "ヤクルト": ("#0B2A5B", "#ffffff", "#8DC63F"),
    "広島": ("#E60012", "#ffffff", "#1a1a1a"),
    "中日": ("#002569", "#ffffff", "#0A7BC2"),
    "ソフトバンク": ("#111111", "#ffffff", "#F8B500"),
    "日本ハム": ("#003B79", "#ffffff", "#A6894B"),
    "西武": ("#102961", "#ffffff", "#E60033"),
    "オリックス": ("#0C2340", "#ffffff", "#B9975B"),
    "楽天": ("#860010", "#ffffff", "#C2A36B"),
    "ロッテ": ("#1F1F1F", "#ffffff", "#A7A9AC"),
}


def team_style(team):
    """見出しの帯（.td-banner）に付ける style 属性。色の無い球団は空文字"""
    c = TEAM_COLORS.get(team)
    if not c:
        return ""
    return f' style="--tm-bg:{c[0]}; --tm-fg:{c[1]}; --tm-line:{c[2]}"'
