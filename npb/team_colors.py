def team_style(team):
    """見出しの帯（.td-banner）に付ける style 属性。色の無い球団は空文字"""
    c = TEAM_COLORS.get(team)
    if not c:
        return ""
    return f' style="--tm-bg:{c[0]}; --tm-fg:{c[1]}; --tm-line:{c[2]}"'


